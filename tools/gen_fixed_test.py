#!/usr/bin/env python3
"""Generates test-g2/fixed.c, which checks floating * and / against exact
Q16.16 results computed here.

Floats are stored as round(x * 65536). On the raw values, a * b is
floor(a * b / 65536) and a / b is floor(a * 65536 / b), wrapped to 32 bits.
The test covers the runtime helpers (__g2_fmul, __g2_fdiv), every inline
form in codegen, and constant folding.

Usage: tools/gen_fixed_test.py > test-g2/fixed.c
"""

import random

INT_MIN = -2**31


def wrap32(v):
    return (v + 2**31) % 2**32 - 2**31


def fix_mul(a, b):
    return wrap32((a * b) >> 16)


def fix_div(a, b):
    return wrap32((a << 16) // b)


def lit(raw):
    """A float literal (or constant expression) with the exact raw value."""
    if raw == INT_MIN:
        return '(float)(-32768)'
    sign = '-' if raw < 0 else ''
    return f'{sign}0x{abs(raw):x}p-16'


def int_lit(n):
    return '(-2147483647 - 1)' if n == INT_MIN else str(n)


def divisible(a, b):
    # g2 traps (or crashes) on these, like integer division does.
    return b != 0 and not (a == INT_MIN and b == -1)


EDGES = [0, 1, -1, 2, 255, 256, 32767, -32768, 32768, 65535, -65535, 65536,
         -65536, 65537, 98304, -98304, 0x1ffff, -0x1ffff, 0x7fff0000, 1 << 30,
         -(1 << 30), 2**31 - 1, INT_MIN, 0x12345678, -0x12345678]

# Constants for the inline forms: whole numbers (a * n), powers of two
# (a / 2^k), the general split, and the edges of the split's f range.
CONSTS = [65536, -65536, 2 * 65536, -3 * 65536, 0, 32768, 16384, -8192, 1,
          -1, 85197, -45875, 6554, 6578114, 2**31 - 1, -2**31 + 1, 32767,
          -32768, 98304, -98304, 163840 + 32767, INT_MIN]

INTS = [0, 1, -1, 2, 3, -7, 100, 32767, -32768, 65536, 2**31 - 1, INT_MIN]


def main():
    rng = random.Random(2026)
    rand = lambda: wrap32(rng.getrandbits(32) >> rng.randrange(32))
    values = EDGES + [rand() for _ in range(8)]

    lines = []
    add = lambda expected, expr: lines.append(f'  ASSERT({int_lit(expected)}, {expr});')

    # Runtime helpers
    pairs = [(a, b) for a in values for b in values]
    rng.shuffle(pairs)
    for a, b in pairs[:300]:
        add(fix_mul(a, b), f'fbits(fv({int_lit(a)}) * fv({int_lit(b)}))')
    n = 0
    for a, b in pairs:
        if divisible(a, b):
            add(fix_div(a, b), f'fbits(fv({int_lit(a)}) / fv({int_lit(b)}))')
            n += 1
            if n == 300:
                break
    # The bit-at-a-time path in __g2_fdiv needs a large remainder.
    for a, b in [(2**31 - 1, 2**30 + 1), (INT_MIN, 2**31 - 1), (2**30, -(2**30) - 7),
                 (-(2**31) + 5, -(2**30) - 1), (1 << 29, 3 << 28), (123456789, 987654321)]:
        add(fix_div(a, b), f'fbits(fv({int_lit(a)}) / fv({int_lit(b)}))')

    # Multiplication and division by constants
    for c in CONSTS:
        for a in values[::2]:
            add(fix_mul(a, c), f'fbits(fv({int_lit(a)}) * {lit(c)})')
            add(fix_mul(c, a), f'fbits({lit(c)} * fv({int_lit(a)}))')
            if divisible(a, c):
                add(fix_div(a, c), f'fbits(fv({int_lit(a)}) / {lit(c)})')

    # Multiplication and division by integers
    for k in INTS:
        for a in values[::3]:
            add(wrap32(a * k), f'fbits(fv({int_lit(a)}) * v({int_lit(k)}))')
            add(wrap32(a * k), f'fbits(v({int_lit(k)}) * fv({int_lit(a)}))')
            if divisible(a, k):
                add(wrap32(a // k), f'fbits(fv({int_lit(a)}) / v({int_lit(k)}))')
        for c in CONSTS[::2]:
            add(wrap32(k * c), f'fbits(v({int_lit(k)}) * {lit(c)})')

    # Constant folding
    for a, b in pairs[:60]:
        add(fix_mul(a, b), f'fbits({lit(a)} * {lit(b)})')
        if divisible(a, b):
            add(fix_div(a, b), f'fbits({lit(a)} / {lit(b)})')

    print('#include "test.h"')
    print()
    print('// Generated by tools/gen_fixed_test.py: floating * and / on Q16.16 raw')
    print('// values, against exact results. fv() and v() hide values from the')
    print('// compiler, so those operations run at run time.')
    print()
    print('int v(int x) { return x; }')
    print('float fv(int raw) { return *(float *)&raw; }')
    print()
    print('void start() {')
    print('\n'.join(lines))
    print('}')


main()
